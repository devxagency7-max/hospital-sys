/**
 * تنظيف الشاشة عند الانتقال.
 *
 * المشكلة التي يحلّها: المكوّنات تُنشئ مستمعات ومؤقتات (بحث مؤجَّل، مستمع نقر
 * على `document`، طلب جارٍ). الراوتر كان ينظّف فقط لو أعادت الشاشة
 * `{ element, destroy }` يدويًا — وهو ما لا يفعله أحد عمليًا، خصوصًا حين يُنشَأ
 * المكوّن داخل تبويب كسول لا يملك الصفحة مرجعًا له.
 *
 * النتيجة الفعلية قبل الإصلاح: بحث مؤجَّل في جدول يُنفَّذ بعد مغادرة الشاشة،
 * فيكتب معاملات الفلترة في رابط الصفحة الجديدة.
 *
 * الحل: سجل تنظيف مرتبط بالانتقال الحالي. المكوّن يُسجّل دالته عند الإنشاء،
 * والراوتر يُشغّل كل الدوال المسجَّلة قبل رسم الشاشة التالية. لا تحتاج الصفحة
 * أن تعرف بوجود المكوّن أصلًا.
 *
 *   // داخل مكوّن
 *   registerCleanup(() => clearInterval(timer));
 */

/** @type {Set<Function>} */
let pending = new Set();

/**
 * يُسجّل دالة تنظيف تُنفَّذ عند الانتقال إلى شاشة أخرى.
 * يُعيد دالة لإلغاء التسجيل — للمكوّن الذي يُفكَّك قبل الانتقال.
 */
export function registerCleanup(fn) {
  if (typeof fn !== "function") return () => {};

  pending.add(fn);
  return () => pending.delete(fn);
}

/**
 * يُشغّل كل دوال التنظيف المسجَّلة ويُفرّغ السجل.
 * يستدعيها الراوتر وحده.
 *
 * فشل دالة لا يمنع البقية: تنظيف نصفي أفضل من تسريب كامل.
 */
export function runCleanups() {
  const toRun = pending;
  pending = new Set();

  for (const fn of toRun) {
    try {
      fn();
    } catch (error) {
      console.error("[lifecycle] فشلت دالة تنظيف:", error);
    }
  }
}

/** عدد الدوال المسجَّلة — للاختبارات وكشف التسريب. */
export function pendingCleanupCount() {
  return pending.size;
}
